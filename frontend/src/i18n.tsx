type Key = keyof typeof STR.en
const Ctx = createContext<{ lang: Lang; t: (k: Key) => string; setLang: (l: Lang) => void }>({ lang: 'en', t: (k) => STR.en[k], setLang: () => {} })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem('rasad.lang') as Lang) || 'en')
  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    localStorage.setItem('rasad.lang', lang)
  }, [lang])
  return <Ctx.Provider value={{ lang, t: (k) => STR[lang][k], setLang }}>{children}</Ctx.Provider>
}

export const useLang = () => useContext(Ctx)

export const yardstick = (p: number, lang: Lang) => {
  const bands: [number, number, string, string][] = [
    [0, 0.075, 'remote chance', 'احتمال بعيد'], [0.075, 0.225, 'highly unlikely', 'مستبعد جداً'], [0.225, 0.375, 'unlikely', 'مستبعد'],
    [0.375, 0.525, 'realistic possibility', 'احتمال واقعي'], [0.525, 0.775, 'likely', 'مرجح'], [0.775, 0.925, 'highly likely', 'مرجح جداً'], [0.925, 1.01, 'almost certain', 'شبه مؤكد'],
  ]
  const b = bands.find(([lo, hi]) => p >= lo && p < hi) ?? bands[bands.length - 1]
  return lang === 'ar' ? b[3] : b[2]
}

export const pct = (p: number | null | undefined) => (p == null ? 'n/a' : `${Math.round(p * 100)}%`)
